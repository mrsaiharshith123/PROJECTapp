function walk(dir, files = []) {
  for (const ent of fs.readdirSync(dir, { withFileTypes: true })) {
    const p = path.join(dir, ent.name);
    if (ent.isDirectory()) {
      if (ent.name === "_archive") continue;
      walk(p, files);
    } else if (/\.(jsx|js)$/.test(ent.name) && !SKIP_FILES.has(ent.name)) {
      files.push(p);
    }
  }
  return files;
}

function migrateFile(fp) {
  let s = fs.readFileSync(fp, "utf8");
  const before = s;
  for (const [from, to] of replacements) {
    if (from) s = s.split(from).join(to);
  }
  s = s.replace(/\s*<div className="ct-hero-glow[^"]*"[^>]*\/?>\s*/g, "\n");
  s = s.replace(/\s*<div className="ed-hero-glow[^"]*"[^>]*\/?>\s*/g, "\n");
  s = s.replace(/className="([^"]*)"/g, (_, cls) => {
    const cleaned = cls.replace(/\s+/g, " ").trim().replace(/  +/g, " ");
    return `className="${cleaned}"`;
  });
  s = s.replace(/className=\{`([^`]*)`\}/g, (_, cls) => {
    const cleaned = cls.replace(/\s+/g, " ").trim();
    return `className={\`${cleaned}\`}`;
  });
  if (s !== before) {
    fs.writeFileSync(fp, s);
    return true;
  }
  return false;
}

const files = walk(root);
let count = 0;
for (const fp of files) {
  if (migrateFile(fp)) {
    count += 1;
    console.log("UPDATED", path.relative(root, fp));
  }
}
console.log(`Done: ${count} files updated`);
